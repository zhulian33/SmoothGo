/**
 * Build miniprogram/data/places.js by running the web app's own merge code.
 *
 * The mini program needs the same 574 venues the web demo counts on its home
 * screen. Those are not simply web/places.poi.js: the web build takes 23
 * hand-written rows, enriches them from the Amap harvest, and then appends the
 * harvest minus rows whose name already resolves to a curated card. Re-typing
 * that pipeline in Python would be faithful for about a week.
 *
 * So instead this script lifts four chunks out of web/app.js, puts them in a
 * Function together with the harvested array, and evaluates them. The web code
 * runs unmodified; if someone fixes the dedupe rule in web/app.js, the mini
 * program picks it up on the next build without anyone remembering to port it.
 *
 * Run via docs/build_miniprogram.py, which copies the shared algorithms too.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const APP = path.join(ROOT, "web", "app.js");
const POI = path.join(ROOT, "web", "places.poi.js");
const OUT = path.join(ROOT, "miniprogram", "data", "places.js");

// Fields the mini program renders. `photos` is the one that matters: it is most
// of the payload and every URL would need an ICP-filed CDN domain.
const KEEP = [
  "id", "name", "type", "category", "featured", "badge", "rating", "avg",
  "lng", "lat", "queueMin", "queueMax", "hours", "visit", "x", "y",
  "interests", "address", "district", "source", "confidence", "icon",
];

/**
 * Index just past the bracket that balances `openAt`, skipping strings,
 * template literals and both comment styles so a `//` inside the data does not
 * swallow the rest of the file.
 */
function matchingBracket(text, openAt) {
  let depth = 0;
  let i = openAt;
  while (i < text.length) {
    const ch = text[i];

    if (ch === "/" && text[i + 1] === "/") {
      const newline = text.indexOf("\n", i);
      i = newline === -1 ? text.length : newline;
      continue;
    }
    if (ch === "/" && text[i + 1] === "*") {
      const close = text.indexOf("*/", i + 2);
      i = close === -1 ? text.length : close + 2;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      const quote = ch;
      i += 1;
      while (i < text.length) {
        if (text[i] === "\\") { i += 2; continue; }
        if (text[i] === quote) { i += 1; break; }
        i += 1;
      }
      continue;
    }
    if (ch === "[" || ch === "{" || ch === "(") { depth += 1; i += 1; continue; }
    if (ch === "]" || ch === "}" || ch === ")") {
      depth -= 1;
      i += 1;
      if (depth === 0) return i;
      continue;
    }
    i += 1;
  }
  throw new Error("unbalanced brackets");
}

function sliceBalanced(text, startIndex, openChar) {
  const openAt = text.indexOf(openChar, startIndex);
  if (openAt === -1) throw new Error(`no ${openChar} after index ${startIndex}`);
  return text.slice(openAt, matchingBracket(text, openAt));
}

function loadGenerated() {
  const source = readFileSync(POI, "utf8");
  return new Function(`${source}; return POI_GENERATED_PLACES;`)();
}

const appSource = readFileSync(APP, "utf8");

// 1. the hand-written rows: everything inside `const PLACES = [ ... ]`
const CURATED_MARKER = "const PLACES = [";
const curatedStart = appSource.indexOf(CURATED_MARKER);
if (curatedStart === -1) throw new Error("cannot find the curated PLACES array");
const curated = sliceBalanced(appSource, curatedStart, "[");

// 2. placeNameKey / chainKey / STREET_SUFFIX, taken straight from above the merge
const HELPERS_MARKER = "const placeNameKey = (name) => {";
const MERGE_MARKER = 'if (typeof POI_GENERATED_PLACES !== "undefined") {';
const helpersStart = appSource.indexOf(HELPERS_MARKER);
const mergeStart = appSource.indexOf(MERGE_MARKER);
if (helpersStart === -1 || mergeStart === -1 || mergeStart < helpersStart) {
  throw new Error("cannot locate the name-key helpers or the merge block");
}
const helpers = appSource.slice(helpersStart, mergeStart);

// 3. the merge itself, evaluated exactly as the browser evaluates it
const merge = sliceBalanced(appSource, mergeStart, "{");

const generated = loadGenerated();
const merged = new Function(
  "POI_GENERATED_PLACES",
  `const PLACES = ${curated};\n${helpers}\n${merge}\nreturn PLACES;`
)(generated);

if (!Array.isArray(merged) || !merged.length) {
  throw new Error("the merge produced no places");
}

const rows = merged.map((place) => {
  const row = {};
  for (const key of KEEP) if (place[key] !== undefined) row[key] = place[key];
  return row;
});

const body = rows
  .map((row) => "  " + JSON.stringify(row))
  .join(",\n");

const header = `/**
 * Generated by docs/mp_extract_places.mjs -- do not edit by hand.
 *
 * ${rows.length} venues, identical to the set the web demo counts on its home
 * screen: ${merged.length - generated.length} hand-written rows plus the Amap
 * harvest deduplicated against them, merged by web/app.js itself.
 *
 * The photo URLs are deliberately absent. Showing them would require every
 * Amap CDN host to be whitelisted as a download domain, and that needs an
 * ICP filing and a registered AppID -- none of which a course demo can get in
 * a week. Without them the mini program makes zero network requests, which is
 * precisely why it runs without one.
 */

module.exports = [
`;

writeFileSync(OUT, header + body + "\n];\n", "utf8");

const curatedCount = rows.filter((row) => row.source === "本地整理").length;
console.log(
  `  generated miniprogram/data/places.js  ${rows.length} places ` +
    `(${curatedCount} curated, ${rows.length - curatedCount} from Amap), ` +
    `${(readFileSync(OUT).byteLength / 1024).toFixed(0)} KB`
);
